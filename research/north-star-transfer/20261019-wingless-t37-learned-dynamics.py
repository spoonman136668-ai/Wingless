"""T37: learned conditional causal rule-bit belief updates over delayed entity data.

A public TRAIN-only conditional relationship model updates the predictive
probability of unknown Boolean transition-rule bits after sequential
intervention observations. Trained parameters actually change the *belief*,
not a rank/order/BDD basis. Probabilities remain distinct from sound exact
certification: only public rule bits shared by all 256 consistent hidden laws
can ever be certified; other future answers receive probabilities alone.
Full categorical empirical Bayes and Beta-pattern controls use identical
public TRAIN, not hidden source law labels. Every exact certification is
independently verified by enumerating all 256 possible 3-input rules.

TRAIN-validation is distinct from TRAIN-meta fitting; original prospective
DEV is NOT generated by either --train-only or --train-cost.
"""
from __future__ import annotations

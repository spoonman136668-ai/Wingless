def evidence(public,src):
    constraints={}
    topology=public["topology"]
    for sequence in public["sequences"]:
        for node,out in sequence["observed"]:
            action=sequence["do"]
            if action is not None and node==action[0]:
                if out!=action[1]:raise RuntimeError("T37_PUBLIC_INTERVENTION_INCONSISTENT")
                continue
            pattern,bit=src.public_answer(topology,sequence["history"],node,out)
            if pattern in constraints and constraints[pattern]!=bit:
                raise RuntimeError("T37_PUBLIC_RULE_BITS_CONTRADICT")
            constraints[pattern]=bit
    return constraints
def all_possible(constraints):
    return tuple(rule for rule in range(256)
          if all(((rule>>p)&1)==v for p,v in constraints.items()))
def learn(src,train):
    meta={f:[] for f in src.FAMILIES}
    for x in train:meta[x["family"]].append(evidence(x,src))
    fitted={}
    for family,cases in meta.items():
        single=[[2.,2.] for _ in range(8)]  # Beta prior, both values supported
        paired=[[[[2.,2.] for _ in range(2)] for _ in range(8)] for _ in range(8)]
        for observed in cases:
            for p,v in observed.items():single[p][v]+=1
            for p,v in observed.items():
                for q,w in observed.items():
                    if p!=q:paired[p][q][v][w]+=1
        bitpriors=tuple(entry[1]/sum(entry) for entry in single)
        # Per-family full 256-rule posterior fit by public-evidence EM.
        prior=[1/256]*256
        for sweep in range(3):
            accum=[0.03/256]*256
            for observed in cases:
                consistent=all_possible(observed)
                denom=sum(prior[law] for law in consistent)
                if denom<=0:raise RuntimeError("T37_TRAIN_FULL_BAYES_ZERO_POSTERIOR")
                for law in consistent:accum[law]+=prior[law]/denom
            total=sum(accum);prior=[p/total for p in accum]
        fitted[family]={"marginal":bitpriors,"conditional":paired,
                        "full_rule_prior":tuple(prior),
                        "training_cases":len(cases)}
    return fitted
def p1(model,observed,pattern,arm):
    if pattern in observed:return float(observed[pattern])
    if arm==ARMS[3]:return 0.5
    base=model["marginal"][pattern]
    if arm==ARMS[2]:return base
    if arm==ARMS[1]:
        laws=all_possible(observed)
        den=sum(model["full_rule_prior"][law] for law in laws)
        if den<=0:raise RuntimeError("T37_BAYES_ZERO_RULE_SUPPORT")
        return sum(model["full_rule_prior"][law] for law in laws if (law>>pattern)&1)/den
    # Trained conditional predictive update: posterior learned correlations
    # between public causal input patterns update a previously unobserved
    # law bit. This is NOT hypothesis sorting; the numerical belief changes.
    conditionals=[]
    for known,v in sorted(observed.items()):
        matrix=model["conditional"][pattern][known]
        hit=matrix[1][v];total=matrix[0][v]+matrix[1][v]
        if total<=0:raise RuntimeError("T37_CONDITIONAL_PRIOR_EMPTY")
        conditional=hit/total
        conditionals.append(conditional)
    if not conditionals:return base
    # Conservative shrink toward trained marginal, never hard-certify a
    # correlation and never give a probability zero or one without proof.
    return 0.4*base+0.6*(sum(conditionals)/len(conditionals))
def infer(public,src,model,arm):
    current=evidence(public,src)
    all_rules=all_possible(current)
    if not all_rules:raise RuntimeError("T37_HIDDEN_RULE_POSTERIOR_EMPTY")
    belief=[]
    for q in public["queries"]:
        node=q["node"];action=q["do"]
        if action is not None and node==action[0]:
            actual={action[1]}
            y=action[1];p=float(y)
        else:
            pattern=src.pattern(*q["history"],public["topology"][node])
            val=p1(model,current,pattern,arm)
            residual=(q["history"][0]>>node)&1
            p=val if not residual else 1-val
            actual={residual^((law>>pattern)&1) for law in all_rules}
        if not 0<=p<=1:raise RuntimeError("T37_INVALID_FORECAST_PROBABILITY")
        cert=next(iter(actual)) if len(actual)==1 else None
        belief.append({"probability":p,"certified":cert,
                       "is_unresolved":cert is None,
                       "consistent_hidden_rule_count":len(all_rules)})
    return belief
def fit_validation():
    src=source()
    if len(src.TRAIN_META)!=40 or len(src.TRAIN_FIT)!=16 or len(src.DEV)!=64:
        raise RuntimeError("T37_COHORT_IDENTITIES_CHANGED")
    assert not (set(src.TRAIN_META)&set(src.TRAIN_FIT)
                or set(src.TRAIN_META)&set(src.DEV)
                or set(src.TRAIN_FIT)&set(src.DEV))
    train=[src.public_META(src.build(s)) for s in src.TRAIN_META]
    fitted=learn(src,train)
    scored={arm:{"sum_square":0.,"unresolved_brier_sum":0.,"n":0,
       "unresolved":0,"correct_certified":0,"hard_false_positives":0,
       "per_case":[]} for arm in ARMS}
    changed_cases=0
    for name in src.TRAIN_FIT:
        original=src.build(name);public=src.public_FIT(original)
        constraints=evidence(public,src)
        if original["_hidden_law"] not in all_possible(constraints):
            raise RuntimeError("T37_TRUE_UNKNOWN_CAUSAL_LAW_EXCLUDED")
        answers={arm:infer(public,src,fitted[public["family"]],arm) for arm in ARMS}
        if any([x["certified"] for x in answers[a]]!=[
             x["certified"] for x in answers[ARMS[3]]] for a in ARMS):
            raise RuntimeError("T37_EXACT_CERTIFICATION_DISAGREEMENT")
        if any(abs(x["probability"]-y["probability"])>1e-9
               for x,y in zip(answers[ARMS[0]],answers[ARMS[2]])):
            changed_cases+=1
        for arm,items in answers.items():
            entry=scored[arm]
            correct=undetermined=0
            for idx,z in enumerate(items):
                truth=original["_truth"][idx]
                brier=(z["probability"]-truth)**2
                entry["sum_square"]+=brier;entry["n"]+=1
                if z["certified"] is None:
                    entry["unresolved"]+=1;entry["unresolved_brier_sum"]+=brier
                    undetermined+=1
                else:
                    if z["certified"]!=truth:raise RuntimeError("T37_FALSE_CERTIFIED_CAUSAL_RULE")
                    entry["correct_certified"]+=1;correct+=1
            entry["per_case"].append({"id":name,"certified":correct,
                "unresolved":undetermined,"truth_evaluation_only":original["_truth"],
                "forecast_probabilities":[round(x["probability"],9) for x in items]})
    for arm,s in scored.items():
        s["Brier_all"]=s["sum_square"]/s["n"]
        s["Brier_unresolved"]=s["unresolved_brier_sum"]/max(s["unresolved"],1)
    best=min(s["Brier_unresolved"] for a,s in scored.items() if a!=ARMS[0])
    candidate=scored[ARMS[0]]["Brier_unresolved"]
    return {"src":src,"fitted":fitted,"scored":scored,
            "Brier_relative_best_control_improvement":(best-candidate)/best if best else 0,
            "causal_parameter_ablation_changed_cases":changed_cases,
            "total_heldout_train_queries":sum(s["n"] for s in scored.values())//len(ARMS)}
def proof():
    v=fit_validation()
    scored=v["scored"]
    arm=ARMS[0]
    s=scored[arm]
    assert s["n"]==64
    assert all(x["hard_false_positives"]==0 for x in scored.values())
    assert all(x["unresolved"]==s["unresolved"] and x["correct_certified"]==s["correct_certified"] for x in scored.values())
    result={"schema":"wingless.T37.TRAIN-only-learned-causal-law-posterior-proof.v1",
        "status":"PASS_TECHNICAL_TRAIN_ONLY","TRAIN_meta_cases":40,
        "TRAIN_validation_cases":16,"DEV_generated":0,
        "TRAIN_true_hidden_rules_preserved":16,
        "TRAIN_counterfactual_forecasts":s["n"],
        "correct_certified":s["correct_certified"],"safely_unresolved":s["unresolved"],
        "hard_false_positives":0,"headroom_fraction":s["unresolved"]/s["n"],
        "learned_weights_change_actual_uncertainty_forecast_cases":v["causal_parameter_ablation_changed_cases"],
        "learned_Brier_unresolved":s["Brier_unresolved"],
        "competitor_Brier_unresolved":{k:z["Brier_unresolved"] for k,z in scored.items() if k!=arm},
        "relative_Brier_improvement_vs_best_strong_control":v["Brier_relative_best_control_improvement"],
        "all_hidden_true_laws_tested_by_independent_256_rule_exact_certifier":True,
        "probability_forecasts_never_called_certified":True,
        "no_previous_DEV_opened":True,"optimizer_admission":False}
    return result
def native_process(arm,repeat):
    if arm not in ARMS or repeat not in range(5):
        raise RuntimeError("T37_INVALID_FROZEN_PROCESS_ARM")
    start=time.process_time_ns()
    src=source()
    train=[src.public_META(src.build(s)) for s in src.TRAIN_META]
    fitted=learn(src,train) if arm!=ARMS[3] else {f:{"marginal":(0.5,)*8,
       "conditional":[],"full_rule_prior":(1/256,)*256} for f in src.FAMILIES}
    score=0.0;unresolved=correct=0
    cases=[]
    for name in src.TRAIN_FIT:
        item=src.build(name);public=src.public_FIT(item)
        pred=infer(public,src,fitted[public["family"]],arm)
        ncert=nunknown=0
        for q,truth in zip(pred,item["_truth"]):
            score+=(q["probability"]-truth)**2
            if q["certified"] is None:unresolved+=1;nunknown+=1
            else:
                if q["certified"]!=truth:raise RuntimeError("T37_CHILD_FALSE_CERTIFICATION")
                correct+=1;ncert+=1
        cases.append({"id":name,"correct_certified":ncert,
             "safe_unresolved":nunknown,
             "probabilities":[round(z["probability"],9) for z in pred]})
    return {"schema":"wingless.T37.TRAIN-only-complete-native-process.v1",
        "arm":arm,"repeat":repeat,"TRAIN_meta_cases":40,"TRAIN_validation_cases":16,
        "DEV_generated":0,"correct_certified":correct,
        "sound_abstentions":unresolved,"hard_false_positives":0,
        "per_case":cases,"Brier_all":score/64,
        "complete_process_CPU_ns":time.process_time_ns()-start,
        "max_peak_RSS_bytes":rss()}
def cost():
    results={}
    for arm in ARMS:
        trials=[]
        for n in range(5):
            p=subprocess.run([sys.executable,str(Path(__file__).resolve()),
                 "--arm",arm,str(n)],capture_output=True,text=True)
            if p.returncode:raise RuntimeError("T37_NATIVE_CHILD_FAILED:"+arm+"\n"+p.stderr[-3000:])
            trials.append(json.loads(p.stdout))
        original=trials[0]
        if any(t["per_case"]!=original["per_case"] for t in trials):
            raise RuntimeError("T37_NONDETERMINISTIC_TRAIN_EVIDENCE")
        results[arm]={"TRAIN_validation_cases":16,"correct_certified":original["correct_certified"],
           "sound_abstentions":original["sound_abstentions"],
           "hard_false_positives":0,"Brier_all":original["Brier_all"],
           "five_complete_CPU_ns":[x["complete_process_CPU_ns"] for x in trials],
           "five_peak_RSS_bytes":[x["max_peak_RSS_bytes"] for x in trials],
           "median_complete_CPU_ns":int(statistics.median(x["complete_process_CPU_ns"] for x in trials)),
           "max_peak_RSS_bytes":max(x["max_peak_RSS_bytes"] for x in trials)}
    candidate=results[ARMS[0]]
    return {"schema":"wingless.T37.TRAIN-native-cost-v1",
        "TRAIN_meta_cases":40,"TRAIN_validation_cases":16,"DEV_generated":0,
        "arms":results,
        "native_all_CPU_better":all(candidate["median_complete_CPU_ns"]<results[a]["median_complete_CPU_ns"] for a in ARMS[1:]),
        "native_RSS_nondegression":candidate["max_peak_RSS_bytes"]<=min(x["max_peak_RSS_bytes"] for x in results.values()),
        "scientific_positive":False,"optimizer_admission":False}
if __name__=="__main__":
    if len(sys.argv)==2 and sys.argv[1]=="--train-only":
        print(json.dumps(proof(),sort_keys=True))
    elif len(sys.argv)==2 and sys.argv[1]=="--train-cost":
        print(json.dumps(cost(),sort_keys=True))
    elif len(sys.argv)==4 and sys.argv[1]=="--arm":
        print(json.dumps(native_process(sys.argv[2],int(sys.argv[3])),sort_keys=True))
    else:raise SystemExit("T37_NO_DEV_MODE_BEFORE_TRAIN_CLEARANCE")

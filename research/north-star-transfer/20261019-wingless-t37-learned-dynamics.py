ARMS=("TRAIN-learned-conditional-causal-belief",
      "TRAIN-fitted-full-rule-empirical-Bayes-256",
      "TRAIN-fitted-independent-Beta-pattern",
      "uniform-exact-version-space")
def source():
    spec=importlib.util.spec_from_file_location("t37_independent_causes",
                 ROOT/"20261019-wingless-t37-sequential-rule-sources.py")
    m=importlib.util.module_from_spec(spec)
    sys.modules[spec.name]=m;spec.loader.exec_module(m);return m
